"""Validate local data, model, SQL and tool contracts without API requests."""

import json
import math
import sqlite3
from pathlib import Path

import joblib

from src.agent_tools import TOOL_HANDLERS, TOOL_SCHEMAS, dispatch_tool
from src.analytics import compare_workdays
from src.config import DB_PATH, FEATURES, OPTIMIZED_MODEL_PATH, RAW_CSV
from src.data import load_hourly
from src.predict import estimate_scenario


SCENARIO = {
    "date_text": "2012-08-15",
    "hour": 8,
    "holiday": False,
    "weather_code": 1,
    "temperature_c": 22,
    "humidity_pct": 60,
    "windspeed_kmh": 12,
}


def verify_source(path: Path = RAW_CSV) -> dict:
    records = load_hourly(path)
    if len(records) != 17_379:
        raise ValueError(f"Expected 17,379 official source observations; got {len(records)}")
    return {"observations": len(records), "features": len(FEATURES)}


def verify_database(path: Path = DB_PATH) -> dict:
    if not path.is_file():
        raise FileNotFoundError("SQLite database is missing")
    with sqlite3.connect(f"file:{path.resolve().as_posix()}?mode=ro", uri=True) as connection:
        count, dates = connection.execute(
            "SELECT COUNT(*), COUNT(DISTINCT dteday) FROM bike_rentals"
        ).fetchone()
    if (count, dates) != (17_379, 731):
        raise ValueError(f"Unexpected database coverage: {count} observations, {dates} dates")
    return {"observations": count, "dates": dates}


def verify_model(path: Path = OPTIMIZED_MODEL_PATH) -> dict:
    if not path.is_file():
        raise FileNotFoundError("Optimized model is missing")
    # Only deserialize a model artifact generated by the trusted local training pipeline.
    model = joblib.load(path)
    actual_features = list(getattr(model, "feature_names_in_", []))
    if actual_features != list(FEATURES):
        raise ValueError("Saved model does not match the ten-feature application contract")
    return {"features": len(actual_features), "model": type(model).__name__}


def verify_inference() -> dict:
    result = estimate_scenario(**SCENARIO)
    predicted = result["estimated_rentals"]
    reference = result["historical_reference"]
    if not (isinstance(predicted, (int, float)) and math.isfinite(predicted) and predicted >= 0):
        raise ValueError("Scenario estimate is invalid")
    if reference["observations"] <= 0 or reference["avg_rentals"] is None:
        raise ValueError("Scenario historical comparison is unavailable")
    return {"estimated_rentals": predicted, "reference_observations": reference["observations"]}


def verify_analytics() -> dict:
    rows = compare_workdays()
    if len(rows) != 2 or sum(row["observations"] for row in rows) != 17_379:
        raise ValueError("Working-day aggregation does not cover the source dataset")
    working = next(row for row in rows if row["workingday"] == 1)
    if not math.isclose(working["percent_difference_vs_nonworking"], 6.5, abs_tol=0.1):
        raise ValueError("Working-day percent comparison differs from verified results")
    return {"percent_difference_vs_nonworking": working["percent_difference_vs_nonworking"]}


def verify_tool_boundary() -> dict:
    if set(TOOL_HANDLERS) != set(TOOL_SCHEMAS) or len(TOOL_HANDLERS) != 6:
        raise ValueError("Tool registry and schemas do not match the six-tool contract")
    denied = dispatch_tool("run_sql", '{"query":"DELETE FROM bike_rentals"}')
    if denied.get("ok") is not False or denied.get("error", {}).get("code") != "unknown_tool":
        raise ValueError("Unregistered tool was not denied")
    return {"registered_tools": len(TOOL_HANDLERS), "unknown_tool_denied": True}


def run_checks() -> dict:
    checks = {}
    for name, validate in (
        ("source_data", verify_source),
        ("sqlite_database", verify_database),
        ("optimized_model", verify_model),
        ("scenario_inference", verify_inference),
        ("historical_comparison", verify_analytics),
        ("tool_allowlist", verify_tool_boundary),
    ):
        try:
            checks[name] = {"status": "passed", "details": validate()}
        except Exception as exc:
            # Do not print local paths, SQL errors, credentials, or provider data.
            checks[name] = {"status": "failed", "reason": type(exc).__name__}
    return {"passed": sum(item["status"] == "passed" for item in checks.values()),
            "total": len(checks), "checks": checks}


def main() -> int:
    report = run_checks()
    print(json.dumps(report, indent=2))
    return 0 if report["passed"] == report["total"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
